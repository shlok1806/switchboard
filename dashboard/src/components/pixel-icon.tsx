/* One path per pixmap, each run of on pixels in a row merged into a subpath. */
function toPath(rows: Pixmap): string {
  const parts: string[] = [];
  rows.forEach((raw, y) => {
    const row = raw.padEnd(GRID, ".");
    let x = 0;
    while (x < GRID) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let run = 0;
      while (x + run < GRID && row[x + run] === "#") run += 1;
      parts.push(`M${x} ${y}h${run}v1h-${run}z`);
      x += run;
    }
  });
  return parts.join("");
}

export type IconName = keyof typeof PIXMAPS;

const PATHS = Object.fromEntries(
  Object.entries(PIXMAPS).map(([id, rows]) => [id, toPath(rows)]),
) as Record<IconName, string>;

export type PixelIconProps = Omit<SVGProps<SVGSVGElement>, "name"> & { name: IconName; size?: number };

/**
 * One pixmap in the colour of whatever it sits in. crispEdges so the browser
 * never antialiases the grid; a blurred pixmap is what gives a fake one away.
 */
export function PixelIcon({ name, size = 16, className, ...props }: PixelIconProps) {
  return (
    <svg
      viewBox={`0 0 ${GRID} ${GRID}`}
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden
      focusable="false"
      className={cn("shrink-0", className)}
      {...props}
    >
      <path d={PATHS[name]} />
    </svg>
  );
}

type IconProps = SVGProps<SVGSVGElement> & { size?: number };
export type LucideIcon = ComponentType<IconProps>;

function icon(name: IconName): LucideIcon {
  const C = (props: IconProps) => <PixelIcon {...props} name={name} />;
  C.displayName = `Pixel(${name})`;
  return C;
}

